-- 4. RPC: record_publisher_profile_change (Diff semântico rigoroso e fallback 'legado')
CREATE OR REPLACE FUNCTION public.record_publisher_profile_change(
    p_publisher_id text, 
    p_prev_data jsonb, 
    p_new_data jsonb, 
    p_source text, 
    p_author_label text, 
    p_author_id text DEFAULT NULL::text, 
    p_token text DEFAULT NULL::text, 
    p_ip text DEFAULT NULL::text, 
    p_ua text DEFAULT NULL::text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    v_publisher_name TEXT;
    v_changed_fields TEXT[] := '{}';
    v_history_id BIGINT;
    v_severity TEXT;
    v_summary TEXT;
    v_critical_fields TEXT[] := ARRAY['privileges','privilegesBySection','gender','restrictions','status','active','isNotQualified','isIndefinitelyPaused'];
    v_meta JSONB;
    v_effective_author TEXT;
BEGIN
    v_publisher_name := COALESCE(p_new_data->>'name', p_prev_data->>'name', p_publisher_id);
    v_effective_author := COALESCE(NULLIF(TRIM(p_author_label), ''), 'legado');

    -- Diff semântico rigoroso: evita falsos positivos de null vs false, null vs "", null vs []
    WITH all_keys AS (
        SELECT DISTINCT k
        FROM (
            SELECT key AS k FROM jsonb_each(COALESCE(p_new_data, '{}'::jsonb))
            UNION
            SELECT key AS k FROM jsonb_each(COALESCE(p_prev_data, '{}'::jsonb))
        ) keys
        WHERE k NOT IN ('availability','availabilityMeta','profileMeta','updatedAt','updatedBy','id')
    )
    SELECT COALESCE(array_agg(DISTINCT k ORDER BY k), '{}')
      INTO v_changed_fields
      FROM all_keys
     WHERE (
        CASE 
            WHEN k IN ('isNotQualified', 'requestedNoParticipation', 'isIndefinitelyPaused', 'isHelperOnly', 'canPairWithNonParent') THEN
                COALESCE((p_prev_data->>k)::boolean, false) IS DISTINCT FROM COALESCE((p_new_data->>k)::boolean, false)
            WHEN k IN ('isServing', 'isBaptized', 'active') THEN
                COALESCE((p_prev_data->>k)::boolean, true) IS DISTINCT FROM COALESCE((p_new_data->>k)::boolean, true)
            WHEN k IN ('phone', 'contact_phone') THEN
                regexp_replace(COALESCE(p_prev_data->>k, ''), '\\D', '', 'g') IS DISTINCT FROM regexp_replace(COALESCE(p_new_data->>k, ''), '\\D', '', 'g')
            WHEN k IN ('notQualifiedReason', 'noParticipationReason', 'indefinitePauseReason', 'email', 'spouseId', 'name', 'gender', 'ageGroup', 'condition', 'funcao', 'address', 'status') THEN
                NULLIF(TRIM(COALESCE(p_prev_data->>k, '')), '') IS DISTINCT FROM NULLIF(TRIM(COALESCE(p_new_data->>k, '')), '')
            WHEN k IN ('parentIds', 'aliases', 'syntheticProfiles') THEN
                COALESCE(p_prev_data->k, '[]'::jsonb) IS DISTINCT FROM COALESCE(p_new_data->k, '[]'::jsonb)
            WHEN k = 'privileges' THEN
                EXISTS (
                    SELECT 1 FROM unnest(ARRAY['canPreside', 'canGiveTalks', 'canGiveStudentTalks', 'canPray', 'canReadCBS', 'canConductCBS']) AS sub_k
                    WHERE COALESCE((p_prev_data->'privileges'->>sub_k)::boolean, false) IS DISTINCT FROM COALESCE((p_new_data->'privileges'->>sub_k)::boolean, false)
                )
            WHEN k = 'privilegesBySection' THEN
                EXISTS (
                    SELECT 1 FROM unnest(ARRAY['canParticipateInTreasures', 'canParticipateInMinistry', 'canParticipateInLife']) AS sub_k
                    WHERE COALESCE((p_prev_data->'privilegesBySection'->>sub_k)::boolean, false) IS DISTINCT FROM COALESCE((p_new_data->'privilegesBySection'->>sub_k)::boolean, false)
                )
            ELSE
                COALESCE(p_prev_data->k, 'null'::jsonb) IS DISTINCT FROM COALESCE(p_new_data->k, 'null'::jsonb)
                AND NOT (
                    (p_prev_data->k IS NULL OR p_prev_data->k = 'null'::jsonb OR p_prev_data->k = '""'::jsonb OR p_prev_data->k = 'false'::jsonb OR p_prev_data->k = '[]'::jsonb)
                    AND
                    (p_new_data->k IS NULL OR p_new_data->k = 'null'::jsonb OR p_new_data->k = '""'::jsonb OR p_new_data->k = 'false'::jsonb OR p_new_data->k = '[]'::jsonb)
                )
        END
     ) = true;

    IF array_length(v_changed_fields, 1) IS NULL OR array_length(v_changed_fields, 1) = 0 THEN
        RETURN jsonb_build_object('success', true, 'no_changes', true);
    END IF;

    -- severity: warning se algum campo crítico, senão info
    IF v_changed_fields && v_critical_fields THEN
        v_severity := 'warning';
    ELSE
        v_severity := 'info';
    END IF;

    v_summary := format('Perfil de %s atualizado por %s (%s campo(s)).',
        v_publisher_name, v_effective_author, array_length(v_changed_fields, 1));

    INSERT INTO public.publisher_profile_history
        (publisher_id, publisher_name, prev_data, new_data, changed_fields,
         source, author_label, author_id, token, ip_address, user_agent)
    VALUES (p_publisher_id, v_publisher_name, p_prev_data, p_new_data, v_changed_fields,
        p_source, v_effective_author, p_author_id,
        CASE WHEN p_token IS NOT NULL THEN substring(p_token, 1, 8) || '…' ELSE NULL END,
        p_ip, p_ua)
    RETURNING id INTO v_history_id;

    INSERT INTO public.publisher_profile_change_notifications
        (history_id, publisher_id, publisher_name, severity, summary, changed_fields,
         affected_part_ids, affected_part_count, source, author_label)
    VALUES (v_history_id, p_publisher_id, v_publisher_name, v_severity, v_summary, v_changed_fields,
        '{}'::uuid[], 0, p_source, v_effective_author);

    -- Stamp metadata em publishers.data.profileMeta (sem alterar restante)
    v_meta := jsonb_build_object(
        'updatedAt', to_char(NOW() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
        'updatedBy', v_effective_author,
        'updatedById', p_author_id,
        'source', p_source,
        'changedFields', to_jsonb(v_changed_fields)
    );
    UPDATE public.publishers
       SET data = jsonb_set(COALESCE(data, '{}'::jsonb), '{profileMeta}', v_meta, true)
     WHERE id = p_publisher_id;

    RETURN jsonb_build_object('success', true, 'historyId', v_history_id,
        'changedFields', to_jsonb(v_changed_fields), 'severity', v_severity);
END;
