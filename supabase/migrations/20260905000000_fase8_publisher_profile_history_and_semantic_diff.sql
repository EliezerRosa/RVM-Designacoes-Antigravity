-- 5. RPC: get_publisher_profile_history_for_form
CREATE OR REPLACE FUNCTION public.get_publisher_profile_history_for_form(
    p_token text DEFAULT NULL::text, 
    p_publisher_id text DEFAULT NULL::text
)
RETURNS TABLE(
    id bigint, 
    publisher_id text, 
    publisher_name text, 
    changed_fields text[], 
    prev_data jsonb, 
    new_data jsonb, 
    source text, 
    author_label text, 
    author_id text, 
    changed_at timestamp with time zone
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_valid boolean := false;
BEGIN
  IF p_token IS NOT NULL AND p_token <> '' THEN
    SELECT EXISTS (
      SELECT 1 FROM publisher_form_tokens
      WHERE token = p_token
        AND revoked_at IS NULL
        AND (expires_at IS NULL OR expires_at > now())
    ) INTO v_valid;
  END IF;

  IF NOT v_valid AND NOT public.is_admin() THEN
    IF auth.uid() IS NOT NULL THEN
      SELECT EXISTS (
        SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin'
      ) INTO v_valid;
    END IF;
  END IF;

  IF NOT v_valid AND NOT public.is_admin() THEN
    RAISE EXCEPTION 'unauthorized' USING ERRCODE = '28000';
  END IF;

  RETURN QUERY
  SELECT 
    h.id,
    h.publisher_id,
    h.publisher_name,
    h.changed_fields,
    h.prev_data,
    h.new_data,
    h.source,
    h.author_label,
    h.author_id,
    h.changed_at
  FROM publisher_profile_history h
  WHERE (p_publisher_id IS NULL OR h.publisher_id = p_publisher_id)
  ORDER BY h.changed_at DESC
  LIMIT 500;
END;
$function$;

-- 6. RPC: dismiss_publisher_profile_notification
CREATE OR REPLACE FUNCTION public.dismiss_publisher_profile_notification(p_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE 
    v_email TEXT;
BEGIN
    IF auth.uid() IS NULL OR NOT public.is_admin() THEN
        RETURN jsonb_build_object('success', false, 'error', 'not_authorized');
    END IF;
    SELECT email INTO v_email FROM profiles WHERE id = auth.uid();
    UPDATE public.publisher_profile_change_notifications
       SET dismissed_at = COALESCE(dismissed_at, now()),
           dismissed_by = COALESCE(dismissed_by, v_email)
     WHERE id = p_id;
    RETURN jsonb_build_object('success', true);
END;
$function$;

-- 7. RPC: update_publisher_profile_history_author (ESTRITAMENTE ADMIN)
CREATE OR REPLACE FUNCTION public.update_publisher_profile_history_author(
    p_history_id bigint DEFAULT NULL::bigint, 
    p_new_author_label text DEFAULT NULL::text, 
    p_publisher_id text DEFAULT NULL::text, 
    p_token text DEFAULT NULL::text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
    v_valid BOOLEAN := false;
    v_publisher_id TEXT := p_publisher_id;
    v_cleaned_author TEXT;
BEGIN
    v_cleaned_author := TRIM(COALESCE(p_new_author_label, ''));
    IF v_cleaned_author = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Autor não pode ser vazio');
    END IF;

    -- 1. Verifica autorização: ESTRITAMENTE ADMIN (tokens e outros papéis NÃO podem corrigir autor)
    IF public.is_admin() THEN
        v_valid := true;
    ELSIF auth.uid() IS NOT NULL THEN
        SELECT EXISTS (
            SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin'
        ) INTO v_valid;
    END IF;

    IF NOT v_valid THEN
        RAISE EXCEPTION 'unauthorized: apenas administradores podem editar ou corrigir o autor do historico' USING ERRCODE = '28000';
    END IF;

    -- 2. Se foi passado history_id, atualiza no histórico
    IF p_history_id IS NOT NULL AND p_history_id > 0 THEN
        UPDATE public.publisher_profile_history
           SET author_label = v_cleaned_author
         WHERE id = p_history_id
        RETURNING publisher_id INTO v_publisher_id;
    END IF;

    -- Se v_publisher_id ainda for nulo e tiver sido passado p_publisher_id
    IF v_publisher_id IS NULL AND p_publisher_id IS NOT NULL THEN
        v_publisher_id := p_publisher_id;
    END IF;

    -- 3. Atualiza também no profileMeta da tabela publishers
    IF v_publisher_id IS NOT NULL THEN
        UPDATE public.publishers
           SET data = jsonb_set(COALESCE(data, '{}'::jsonb), '{profileMeta,updatedBy}', to_jsonb(v_cleaned_author), false)
         WHERE id = v_publisher_id
           AND data ? 'profileMeta';
    END IF;

    RETURN jsonb_build_object(
        'success', true, 
        'publisher_id', v_publisher_id, 
        'history_id', p_history_id, 
        'new_author_label', v_cleaned_author
    );
END;
$function$;
